import enum
import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, ForeignKey, String, UniqueConstraint
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import BaseModel


class LanPairingSession(BaseModel):
    """
    Short-lived pairing code generated by an authorized business user on the Windows coordinator.
    Used by Android devices on the LAN to securely pair and establish a LAN session.
    """
    __tablename__ = "lan_pairing_sessions"

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    created_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )

    pairing_code: Mapped[str] = mapped_column(String(16), nullable=False, index=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    is_claimed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    claimed_by_device_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("client_devices.id", ondelete="SET NULL"),
        nullable=True,
    )
    claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    business = relationship("Business")
    created_by = relationship("User")
    claimed_device = relationship("ClientDevice")


class LanDevicePairing(BaseModel):
    """
    Durable record of an authenticated paired device and its active LAN session token.
    Allows paired Android devices to relay transactions to the Windows coordinator during outages.
    """
    __tablename__ = "lan_device_pairings"
    __table_args__ = (
        UniqueConstraint("business_id", "device_id", name="uq_lan_device_pairing_biz_device"),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    device_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("client_devices.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    lan_token_hash: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    token_expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    is_revoked: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    business = relationship("Business")
    device = relationship("ClientDevice")
